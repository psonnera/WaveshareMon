static void drawIcon(int16_t x, int16_t y, const unsigned char *bitmap, uint16_t color) {
  display.drawBitmap(x, y, bitmap, 16, 16, color);
}

enum Align { AL_LEFT, AL_CENTER, AL_RIGHT };

// draw text with its top-left / top-center / top-right at (x, y)
static int16_t drawText(const char *s, int16_t x, int16_t y, const GFXfont *font, uint8_t size,
                        uint16_t color, Align al = AL_LEFT) {
  int16_t bx, by; uint16_t bw, bh;
  display.setFont(font);
  display.setTextSize(size);
  display.setTextColor(color);
  display.getTextBounds(s, 0, 0, &bx, &by, &bw, &bh);
  int16_t x0 = x;
  if (al == AL_CENTER) x0 = x - bw / 2;
  else if (al == AL_RIGHT) x0 = x - bw;
  display.setCursor(x0 - bx, y - by);
  display.print(s);
  return bw;
}

static void textSize(const char *s, const GFXfont *font, uint8_t size, uint16_t &w, uint16_t &h) {
  int16_t bx, by;
  display.setFont(font);
  display.setTextSize(size);
  display.getTextBounds(s, 0, 0, &bx, &by, &w, &h);
}

// 16x16 icon drawn at twice its size (32x32 cell); Adafruit GFX has no bitmap scaling
static void drawIcon2x(int16_t x, int16_t y, const unsigned char *bitmap, uint16_t color) {
  for (int row = 0; row < 16; row++)
    for (int col = 0; col < 16; col++)
      if (bitmap[row * 2 + col / 8] & (0x80 >> (col % 8)))
        display.fillRect(x + col * 2, y + row * 2, 2, 2, color);
}

// solid pointer (the silhouette of the U+27A4 arrow) of length len, centred at (cx, cy),
// pointing at angleDeg: -90 up, 0 right (flat), 90 down. Screen y grows downwards, so the
// NightscoutMon angle convention rotates directly.
static void drawPointer(int cx, int cy, int angleDeg, int len, uint16_t color) {
  float a = angleDeg * (float)PI / 180.0f, ca = cosf(a), sa = sinf(a);
  auto rx = [&](float x, float y) { return (int16_t)lroundf(cx + x * ca - y * sa); };
  auto ry = [&](float x, float y) { return (int16_t)lroundf(cy + x * sa + y * ca); };
  float half = len / 2.0f, wing = len * 0.42f, notch = -half + len * 0.3f;
  // two triangles sharing the tip-notch edge give the concave back
  display.fillTriangle(rx(half, 0), ry(half, 0), rx(-half, -wing), ry(-half, -wing),
                       rx(notch, 0), ry(notch, 0), color);
  display.fillTriangle(rx(half, 0), ry(half, 0), rx(notch, 0), ry(notch, 0),
                       rx(-half, wing), ry(-half, wing), color);
}

// trend: one pointer for flat / 45 / single, two stacked for double up / down (xDrip's
// double arrows), which are otherwise only 15 degrees apart from the single ones
static void drawTrend(int cx, int cy, int angle, uint16_t color) {
  if (angle <= -90 || angle >= 90) {
    drawPointer(cx, cy - 13, angle, 24, color);
    drawPointer(cx, cy + 13, angle, 24, color);
  } else {
    drawPointer(cx, cy, angle, 36, color);
  }
}

// colour band for the current value: 0 normal, 1 yellow warning, 2 red alarm
static int valueLevel() {
  if (!gs.hasData) return 0;
  if (gs.mgdl < cfg.redLow || gs.mgdl > cfg.redHigh) return 2;
  if (gs.mgdl < cfg.yellowLow || gs.mgdl > cfg.yellowHigh) return 1;
  return 0;
}

