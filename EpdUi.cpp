void EpdUi::drawHeader() {
  // from the right: battery icon, battery %, link icon, snooze clock; reading time
  // on the left. The icons are the 16x16 art at 2x; the link / clock art has 4 blank
  // columns on each side (8 px at 2x), which the fit test counts as spacing.
  int pct = battery.percent();
  char pt[8] = "";
  if (pct >= 0) snprintf(pt, sizeof(pt), "%d%%", pct);
  char t[12] = "";
  if (gs.hasData && gs.readingUtc) timeService.formatTime(gs.readingUtc, t, sizeof(t));
  bool snoozed = alarms.isSnoozed();

  // the percentage only when there is room: 11 pt, else 9 pt, else dropped, keeping
  // the time at 18 pt as long as possible (a 12 h time is wider and may drop to 12 pt).
  const GFXfont *cand[][2] = {
    { &FreeSansBold18pt7b, &FreeSansBold11pt7b }, { &FreeSansBold18pt7b, &FreeSansBold9pt7b },
    { &FreeSansBold18pt7b, nullptr },
    { &FreeSansBold12pt7b, &FreeSansBold11pt7b }, { &FreeSansBold12pt7b, &FreeSansBold9pt7b },
    { &FreeSansBold12pt7b, nullptr } };
  const GFXfont *tf = &FreeSansBold12pt7b, *pf = nullptr;
  uint16_t w, h, tw = 0, th = 0, pw = 0, ph = 0;
  int linkX = 0;
  for (auto &c : cand) {
    uint16_t ctw = 0, cth = 0, cpw = 0, cph = 0;
    if (t[0]) { textSize(t, c[0], 1, w, h); ctw = w; cth = h; }
    if (pt[0] && c[1]) { textSize(pt, c[1], 1, w, h); cpw = w; cph = h; }
    int lx = W - 32 - (cpw ? cpw + 6 : 0) - 32;          // link icon cell
    int leftmost = lx - (snoozed ? 32 : 0) + 8;           // first visible icon column
    tf = c[0]; pf = cpw ? c[1] : nullptr; tw = ctw; th = cth; pw = cpw; ph = cph; linkX = lx;
    if (2 + ctw + 4 <= leftmost) break;
  }

  int x = W - 32;
  if (battery.onUsb() && pct < 0) drawIcon2x(x, 0, plug_icon16x16, GxEPD_BLACK);
  else if (pct >= 0) {
    const unsigned char *ic = pct <= 12 ? bat0_icon16x16 : pct <= 40 ? bat1_icon16x16 :
                              pct <= 65 ? bat2_icon16x16 : pct <= 90 ? bat3_icon16x16 : bat4_icon16x16;
    uint16_t c = pct <= 12 ? GxEPD_RED : GxEPD_BLACK;
    drawIcon2x(x, 0, ic, c);
    if (pf) drawText(pt, x - 3, (HDR_H - ph) / 2, pf, 1, c, AL_RIGHT);
  }
  x = linkX;
  if (cfg.source == SRC_OBB) {
    ObbState s = obbState();
    uint16_t c = s == OBB_CONNECTED ? GxEPD_BLACK : GxEPD_RED;
    drawIcon2x(x, 0, bluetooth_icon16x16, c);
  } else if (cfg.source == SRC_MIBAND) {
    // in the power cycle the link is closed again before the screen refreshes:
    // black as long as xDrip has paired, red until the first key exchange
    bool ok = miBandIsAuthenticated() || (!cycleAwake() && cfg.mibandKeySet);
    drawIcon2x(x, 0, bluetooth_icon16x16, ok ? GxEPD_BLACK : GxEPD_RED);
  } else {
    drawIcon2x(x, 0, wifi2_icon16x16, wifiConnected() ? GxEPD_BLACK : GxEPD_RED);
  }
  if (snoozed) drawIcon2x(x - 32, 0, clock_icon16x16, GxEPD_RED);

  if (t[0]) drawText(t, 2, (HDR_H - th) / 2, tf, 1, GxEPD_BLACK);
}

void EpdUi::drawValue() {
  // a reading STALE_MIN or older is no longer shown at all: "---" without band or
  // pointer (the age on the right says how old it is); LATE_MIN..STALE_MIN is
  // crossed out
  bool stale = gs.hasData && gs.isStale();
  bool late = gs.hasData && !stale && (gs.isLate() || !gs.live);
  char v[12];
  if (stale) strlcpy(v, "---", sizeof(v));
  else gs.valueString(v, sizeof(v), cfg.isMgdl());
  // 28 pt digits (~40 px) leave room for the trend pointer on the right
  const GFXfont *font = strlen(v) > 4 ? &FreeSansBold18pt7b : &FreeSansBold28pt7b;
  uint16_t tw, th;
  textSize(v, font, 1, tw, th);
  // the band encloses value, pointer, delta and age: red / yellow fill outside the
  // colour range or while an alarm / warning is active, a rounded 2 px frame in range,
  // nothing once the value reads "---" (unless an alarm state says otherwise)
  int level = stale ? 0 : valueLevel();
  AlarmState as = alarms.state();
  int alarmLevel = (as == ALARM_ALARM_LOW || as == ALARM_ALARM_HIGH || as == ALARM_REMOTE) ? 2 :
                   (as == ALARM_NONE) ? 0 : 1;
  if (alarmLevel > level) level = alarmLevel;
  uint16_t fg = GxEPD_BLACK;
  if (level == 2) { display.fillRoundRect(2, BAND_TOP, W - 4, BAND_H, 8, GxEPD_RED); fg = GxEPD_WHITE; }
  else if (level == 1) { display.fillRoundRect(2, BAND_TOP, W - 4, BAND_H, 8, GxEPD_YELLOW); }
  else if (gs.hasData && !stale) {
    display.drawRoundRect(2, BAND_TOP, W - 4, BAND_H, 8, GxEPD_BLACK);
    display.drawRoundRect(3, BAND_TOP + 1, W - 6, BAND_H - 2, 7, GxEPD_BLACK);
  }
  bandFg = fg;
  int ty = VAL_TOP + (VAL_H - th) / 2;
  drawText(v, VAL_CX, ty, font, 1, fg, AL_CENTER);
  if (late) {
    // strike-through: the value can no longer be trusted
    int y = ty + th / 2;
    display.fillRect(VAL_CX - tw / 2 - 6, y - 2, tw + 12, 5, level == 2 ? GxEPD_WHITE : GxEPD_RED);
  }
  // trend pointer, right of the value, in the band's foreground colour
  if (gs.hasData && gs.arrowAngle != ARROW_HIDDEN && !stale)
    drawTrend(ARROW_CX, ARROW_CY, gs.arrowAngle, fg);
}

void EpdUi::drawTrendRow() {
  uint16_t tw, th;
  // delta (left)
  char d[12];
  if (gs.hasData && gs.isStale()) strlcpy(d, "---", sizeof(d));
  else gs.deltaString(d, sizeof(d), cfg.isMgdl());
  textSize(d, &FreeSansBold18pt7b, 1, tw, th);
  drawText(d, 10, TREND_Y + (TREND_H - th) / 2, &FreeSansBold18pt7b, 1, bandFg);
  // age (right)
  char age[16];
  if (!gs.hasData) age[0] = 0;
  else {
    int m = gs.minutesAgo();
    if (m < 60) snprintf(age, sizeof(age), "%d min", m);
    else if (m < 1440) snprintf(age, sizeof(age), "%dh%02d", m / 60, m % 60);
    else strlcpy(age, "old", sizeof(age));
  }
  if (!age[0]) return;
  textSize(age, &FreeSansBold18pt7b, 1, tw, th);
  // a late age is red, except on the red band where everything is white
  uint16_t c = gs.isLate() && bandFg != GxEPD_WHITE ? GxEPD_RED : bandFg;
  drawText(age, W - 10, TREND_Y + (TREND_H - th) / 2, &FreeSansBold18pt7b, 1, c, AL_RIGHT);
}

void EpdUi::drawGraph(int y0, int hgt) {
  // the last GRAPH_PTS samples (2 h), newest at the right edge. The scale follows the
  // data around the yellow band so the curve uses the full height instead of a fixed
  // 40..300 mg/dL range.
  const int x0 = GRAPH_X, gw = GRAPH_PTS * GRAPH_PITCH;
  int n = gs.histCount, first = n > GRAPH_PTS ? n - GRAPH_PTS : 0;
  float lo = cfg.yellowLow - 10, hi = cfg.yellowHigh + 10;
  for (int i = first; i < n; i++) {
    uint16_t v = gs.hist[i];
    if (v == 0) continue;
    if (v < lo) lo = v;
    if (v > hi) hi = v;
  }
  if (lo < 40) lo = 40;
  if (hi > 300) hi = 300;
  if (hi - lo < 50) hi = lo + 50;
  auto yOf = [&](float mg) {
    if (mg > hi) mg = hi; if (mg < lo) mg = lo;
    return (int)(y0 + hgt - 1 - (mg - lo) * (hgt - 1) / (hi - lo));
  };
  auto threshold = [&](int mg, uint16_t c) {
    if (mg >= lo && mg <= hi) display.drawFastHLine(x0, yOf(mg), gw, c);
  };
  threshold(cfg.yellowHigh, GxEPD_YELLOW);
  threshold(cfg.yellowLow, GxEPD_YELLOW);
  threshold(cfg.redHigh, GxEPD_RED);
  threshold(cfg.redLow, GxEPD_RED);
  for (int i = first; i < n; i++) {
    uint16_t v = gs.hist[i];
    if (v == 0) continue;
    int x = x0 + (GRAPH_PTS - (n - i)) * GRAPH_PITCH;
    uint16_t c = GxEPD_BLACK;
    if (v < cfg.redLow || v > cfg.redHigh) c = GxEPD_RED;
    display.fillCircle(x, yOf(v), 1, c);
    display.drawPixel(x, yOf(v) - 1, c);
  }
}

// info line (IOB / COB from Nightscout, or the phone's status line) beside the graph,
// on up to two rows split at a double space; text too wide stays on the bottom bar
bool EpdUi::drawSideText() {
  if (!gs.infoLine[0]) return false;
  char rows[2][48];
  int nr = 1;
  const char *s = gs.infoLine, *sep = strstr(s, "  ");
  if (sep) {
    size_t l = sep - s;
    if (l >= sizeof(rows[0])) l = sizeof(rows[0]) - 1;
    memcpy(rows[0], s, l); rows[0][l] = 0;
    while (*sep == ' ') sep++;
    strlcpy(rows[1], sep, sizeof(rows[1]));
    nr = 2;
  } else {
    strlcpy(rows[0], s, sizeof(rows[0]));
  }
  for (int i = 0; i < nr; i++) {
    uint16_t w, h;
    textSize(rows[i], &FreeSansBold11pt7b, 1, w, h);
    if (w > SIDE_W) return false;
  }
  for (int i = 0; i < nr; i++)
    drawText(rows[i], SIDE_X, GRAPH_Y + 2 + i * 20, &FreeSansBold11pt7b, 1, GxEPD_BLACK);
  return true;
}

void EpdUi::drawBottomBar(bool infoShown) {
  const int y = BAR_Y;
  const char *alarm = alarms.label();
  if (alarm[0]) {
    AlarmState s = alarms.state();
    bool red = s == ALARM_ALARM_LOW || s == ALARM_ALARM_HIGH || s == ALARM_REMOTE;
    display.fillRect(0, y, W, BAR_H, red ? GxEPD_RED : GxEPD_YELLOW);
    char txt[40];
    int sn = alarms.snoozeRemainingMin();
    if (sn) snprintf(txt, sizeof(txt), "%s  zz %d'", alarm, sn);
    else strlcpy(txt, alarm, sizeof(txt));
    uint16_t tw, th;
    const GFXfont *font = &FreeSansBold12pt7b;
    textSize(txt, font, 1, tw, th);
    if (tw > W - 4) { font = &FreeSansBold9pt7b; textSize(txt, font, 1, tw, th); }
    drawText(txt, W / 2, y + (BAR_H - th) / 2, font, 1, red ? GxEPD_WHITE : GxEPD_BLACK, AL_CENTER);
    return;
  }
  // status text: setup mode > connection state > info line (unless it is already
  // shown beside the graph). In the power cycle the radios are off between wakes,
  // so only a persistent failure of the last fetch is shown, never the transient
  // link state.
  char txt[96];
  if (setupServerAdvertising())
    snprintf(txt, sizeof(txt), "Setup: %s", cfg.name());
  else if (!cycleAwake() && cycleStatusText()[0])
    strlcpy(txt, cycleStatusText(), sizeof(txt));
  else if (!cycleAwake() && gs.infoLine[0] && !infoShown)
    strlcpy(txt, gs.infoLine, sizeof(txt));
  else if (!cycleAwake())
    txt[0] = 0;
  else if (cfg.source == SRC_OBB && obbState() != OBB_CONNECTED)
    snprintf(txt, sizeof(txt), "xDrip: %s", obbStateName());
  else if (cfg.source == SRC_MIBAND && !miBandIsAuthenticated())
    snprintf(txt, sizeof(txt), "xDrip: %s", miBandStateName());
  else if (SRC_IS_WIFI(cfg.source) && !wifiConnected())
    snprintf(txt, sizeof(txt), "Wi-Fi: %s", wifiFailText()[0] ? wifiFailText() : wifiStateName());
  else if (cfg.source == SRC_DEXCOM && dxStatus()[0])
    strlcpy(txt, dxStatus(), sizeof(txt));
  else if (cfg.source == SRC_LIBRE && llStatus()[0])
    strlcpy(txt, llStatus(), sizeof(txt));
  else if (gs.infoLine[0] && !infoShown)
    strlcpy(txt, gs.infoLine, sizeof(txt));
  else
    txt[0] = 0;
  if (txt[0]) {
    uint16_t tw, th;
    textSize(txt, &FreeSans9pt7b, 1, tw, th);
    display.drawFastHLine(0, y, W, GxEPD_BLACK);
    drawText(txt, W / 2, y + 1 + (BAR_H - 1 - th) / 2, &FreeSans9pt7b, 1, GxEPD_BLACK, AL_CENTER);
  }
}

